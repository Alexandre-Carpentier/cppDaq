///////////////////////////////////////////////////////////////////////////////////////
//
// Hardware configuration for NI USB 6001 (must be edited)
//
// Wiring: NI USB-6001 <-> Lexitek R208 (DB9 connector)
// See hardware/doc.md for full wiring diagram.
//
//  NI USB-6001 Pin | Signal        | R208 DB9 Pin | Description
// -----------------|---------------|--------------|----------------------------
//  AI0             | HOME_PIN      | Pin 5        | Home position sensor (analog voltage)
//  AO0             | CLOCK_PIN     | Pin 2        | PWM step signal (generated continuously for greater frequencies)
//  AO0             | SW_CLOCK_PIN  | Pin 2        | PWM step signal (generated manually by software for precision)
//  P0.0            | MOVE_PIN      | Pin 4        | Motor enable/disable
//  P0.1            | DIR_PIN       | Pin 3        | Rotation direction
//  AGND / GND      | GND           | Pin 1        | Common ground
//

// inline to prevent multiple definitions
inline analog_input_pin HOME_PIN{ 0 };				// AI0  → R208 DB9 Pin 5 : Home position sensor
inline analog_pin_continuous CLOCK_PIN{ 0 };	// AO0  → R208 DB9 Pin 2 : PWM step signal (generated continuously for greater frequencies)
inline analog_output_pin SW_CLOCK_PIN{ 0 };			// AO0  → R208 DB9 Pin 2 : PWM step signal (generated manually by software for precision)
inline digital_pin MOVE_PIN{ 0 };				// P0.0 → R208 DB9 Pin 4 : Motor enable (HIGH = active)
inline digital_pin DIR_PIN{ 1 };				// P0.1 → R208 DB9 Pin 3 : Direction (HIGH = CW, LOW = CCW)

///////////////////////////////////////////////////////////////////////////////////////
//
// Dependencies injection
//

class hardware_interface
{
public:
	virtual bool start(double freqHz) = 0;
	virtual bool stop() = 0;
	virtual bool resetDaq() = 0;
	virtual void acquires(double& voltage) = 0;
	virtual bool setSpeed(double freqHz) = 0;
	virtual bool doMove(bool isMoving) = 0; // Turn when isMoving = true, Stop when isMoving = false
	virtual bool moveTo(int64_t clockCount) = 0; // Move to a specific clock count (for future use)
	virtual void doClockwizeDirection(bool isClockWise) = 0;
	virtual bool checkDaq() = 0;
	virtual ~hardware_interface() = default; // Mandatory for childrens
};

///////////////////////////////////////////////////////////////////////////////////////
//
// Time based hardware code
//

// This class is used to generate a PWM signal on the CLOCK_PIN using hardaware control.
// This is using the same PIN as Clock based hardware, the signal is generated by the hardware for speed (but less precision).
class timeBased_hardware : public hardware_interface
{
public:
	timeBased_hardware()
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		std::print("[*] Initialize timeBased_hardware\n");
		std::print("[*] Connecting to DAQ\n");

		DaqConfig config;

		config.setDevice("Dev1") // Auto connect to first device if empty. Default name is Dev1 if needed.
			.setAnalogInputPins(analog_input_pins{ HOME_PIN }) // To read home position
			.setAnalogOutputPins(analog_output_pins{ CLOCK_PIN }) // To make a PWM signal
			.setDigitalPins(digital_pins{ MOVE_PIN, DIR_PIN }); // To control the direction and the movement

		m_daq = std::make_unique<cppDaq>(config);
		assert(m_daq); // Ensure DAQ is initialized correctly
	}

	bool start(double freqHz) override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		std::print("[*] Starting hardware\n");
		m_freqHz = freqHz;

		m_daq->WriteDigitalPin(DIR_PIN, 1.0);  // TURN CLOCKWIZE
		m_daq->WriteDigitalPin(MOVE_PIN, 0.0); // MOVE ON
		m_running = true;
		return true;
		//return m_daq->StartAnalogPWM(CLOCK_PIN, Frequency_hz<double>(freqHz));
	}

	bool stop() override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		std::print("[*] Stopping hardware\n");

		m_daq->WriteDigitalPin(DIR_PIN, 1.0);  // TURN CLOCKWIZE
		m_daq->WriteDigitalPin(MOVE_PIN, 1.0); // MOVE OFF
		m_running = false;
		m_daq->StopAnalogPWM(CLOCK_PIN);

		std::this_thread::sleep_for(std::chrono::milliseconds(500)); // Give some time for the DAQ to reset
		return true;
	}

	virtual bool resetDaq() override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		std::print("[*] Reseting hardware\n");
		return m_daq->resetDaq();
	}

	virtual void acquires(double& voltage)
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		voltage = m_daq->ReadAnalogPin(HOME_PIN);
	}

	virtual bool setSpeed(double freqHz) override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		m_freqHz = freqHz;

		if (m_running)
		{
			m_daq->StopAnalogPWM(CLOCK_PIN);
		}
		std::print("[*] Setting speed to {} Hz\n", freqHz);
		return m_daq->StartAnalogPWM(CLOCK_PIN, Frequency_hz<double>(m_freqHz));
	}

	virtual bool doMove(bool isMoving) override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		static bool s_state = false;
		if (isMoving != s_state) // Only update if s_state changed	
		{
			s_state = isMoving; // Save state

			//Act
			if (isMoving)
			{
				std::print(CYN"[*] doMove(true) called\n"); std::print(NC);
				//m_daq->WriteDigitalPin(MOVE_PIN, digital_state::LOW); // Enable			
				return m_daq->StartAnalogPWM(CLOCK_PIN, Frequency_hz<double>(m_freqHz));
			}
			std::print(CYN"[*] doMove(false) called\n"); std::print(NC);
			//m_daq->WriteDigitalPin(MOVE_PIN, digital_state::HIGH); // Disable
			return m_daq->StopAnalogPWM(CLOCK_PIN);
		}
		return true;
	}

	virtual bool moveTo(int64_t clockCount) override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		std::print(CYN"[*] moveTo({}) called\n", clockCount); std::print(NC);
		return true;
	}

	virtual void doClockwizeDirection(bool isClockWise) override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		static bool s_lastDirection = true;
		if (isClockWise != s_lastDirection)
		{
			s_lastDirection = isClockWise;

			std::print(CYN"[*] clockWize = {}\n", isClockWise); std::print(NC);

			if (isClockWise == true)
			{
				std::print(CYN"[*] WRITE HIGH\n"); std::print(NC);
				m_daq->WriteDigitalPin(DIR_PIN, 1.0);// turn anticlockwise
			}
			else if (isClockWise == false)
			{
				std::print(CYN"[*] WRITE LOW\n"); std::print(NC);
				m_daq->WriteDigitalPin(DIR_PIN, 0.0);// turn clockwise
			}
		}
	}

	virtual bool checkDaq() override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		bool isOk = true;
		if (m_daq->GetStatus() != DAQ_STATUS::NO_ERR)
		{
			isOk = false;
		}
		return isOk;
	}
private:
	std::unique_ptr<cppDaq> m_daq = nullptr;
	double m_freqHz{ 0.0 };
	bool m_running = false;

	std::mutex m_mutexAPI;
};

///////////////////////////////////////////////////////////////////////////////////////
//
// Clock based code
//

// This class is used to generate a PWM signal on the SW_CLOCK_PIN using software control.
// This is using the same PIN as Time based hardware, but the signal is generated manually by software for precision (but slower).
class clockBased_hardware : public hardware_interface
{
public:
	clockBased_hardware()
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		std::print("[*] Initialize clockBased_hardware\n");
		std::print("[*] Connecting to DAQ\n");

		DaqConfig config;

		config.setDevice("Dev1") // Auto connect to first device if empty. Default name is Dev1 if needed.
			.setAnalogInputPins(analog_input_pins{ HOME_PIN }) // To read home position
			.setAnalogOutputPins(analog_output_pins{ SW_CLOCK_PIN }) // To make a PWM signal
			.setDigitalPins(digital_pins{ MOVE_PIN, DIR_PIN }); // To control the direction and the movement

		m_daq = std::make_unique<cppDaq>(config);
		assert(m_daq); // Ensure DAQ is initialized correctly
	}

	bool start(double freqHz) override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		std::print("[*] Starting hardware\n");
		m_freqHz = freqHz;

		m_daq->WriteDigitalPin(DIR_PIN, 1.0);  // TURN CLOCKWIZE
		m_daq->WriteDigitalPin(MOVE_PIN, 0.0); // MOVE ON
		m_daq->WriteAnalogPin(SW_CLOCK_PIN, 0.0); // PWM LOW
		m_running = true;
		return true;
	}

	bool stop() override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		std::print("[*] Stopping hardware\n");

		m_daq->WriteDigitalPin(DIR_PIN, 1.0);  // TURN CLOCKWIZE
		m_daq->WriteDigitalPin(MOVE_PIN, 1.0); // MOVE OFF
		m_running = false;
		m_daq->WriteAnalogPin(SW_CLOCK_PIN, 0.0); // PWM LOW

		std::this_thread::sleep_for(std::chrono::milliseconds(500)); // Give some time for the DAQ to reset
		return true;
	}

	virtual bool resetDaq() override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		std::print("[*] Reseting hardware\n");
		return m_daq->resetDaq();
	}

	virtual void acquires(double& voltage)
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		voltage = m_daq->ReadAnalogPin(HOME_PIN);
	}

	virtual bool setSpeed(double freqHz) override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		m_freqHz = freqHz;

		if (m_running)
		{
			m_daq->WriteAnalogPin(SW_CLOCK_PIN, 0.0); // PWM LOW
		}
		std::print("[*] Setting speed to {} Hz\n", freqHz);
		return true;
	}

	virtual bool doMove(bool isMoving) override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);

		static bool s_state = false;
		if (isMoving)
		{
			m_daq->WriteAnalogPin(SW_CLOCK_PIN, 3.3); // PWM HIGH
			std::this_thread::sleep_for(std::chrono::microseconds(static_cast<int>(1e6 / m_freqHz/2))); // Wait for the duration of one clock cycle
			m_daq->WriteAnalogPin(SW_CLOCK_PIN, 0.0); // PWM LOW
			std::this_thread::sleep_for(std::chrono::microseconds(static_cast<int>(1e6 / m_freqHz/2))); // Wait for the duration of one clock cycle
			s_state = false; // Save state
		}
		else
		{
			if (isMoving == s_state) // Only update if s_state changed
			{
				s_state = true; // Save state
				m_daq->WriteAnalogPin(SW_CLOCK_PIN, 0.0); // PWM LOW
			}
		}


		return true;

	}

	virtual bool moveTo(int64_t clockCount) override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		std::print(CYN"[*] moveTo({}) called\n", clockCount); std::print(NC);
		return true;
	}

	virtual void doClockwizeDirection(bool isClockWise) override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		static bool s_lastDirection = true;
		if (isClockWise != s_lastDirection)
		{
			s_lastDirection = isClockWise;

			std::print(CYN"[*] clockWize = {}\n", isClockWise); std::print(NC);

			if (isClockWise == true)
			{
				std::print(CYN"[*] WRITE HIGH\n"); std::print(NC);
				m_daq->WriteDigitalPin(DIR_PIN, 1.0);// turn anticlockwise
			}
			else if (isClockWise == false)
			{
				std::print(CYN"[*] WRITE LOW\n"); std::print(NC);
				m_daq->WriteDigitalPin(DIR_PIN, 0.0);// turn clockwise
			}
		}
	}

	virtual bool checkDaq() override
	{
		std::lock_guard<std::mutex> lockInit(m_mutexAPI);
		bool isOk = true;
		if (m_daq->GetStatus() != DAQ_STATUS::NO_ERR)
		{
			isOk = false;
		}
		return isOk;
	}
private:
	std::unique_ptr<cppDaq> m_daq = nullptr;
	double m_freqHz{ 0.0 };
	bool m_running = false;

	std::mutex m_mutexAPI;
};

int main()
{
	clockBased_hardware clk;
	clk.start(10.0);

	double measure = 0.0;
	clk.acquires(measure);

	for (int i = 0; i < 1000; ++i)
	{
		clk.doMove(true);
	}

	clk.doMove(false);
	clk.stop();
	return 0;
}